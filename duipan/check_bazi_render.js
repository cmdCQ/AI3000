/**
 * 八字报告的**渲染**检查：规范里要求的那种输出，前端真能渲染成想要的样子吗？
 * ==========================================================================
 *
 * 存在理由：`bazi_report.js` 的规范是在**文字层**定死的（一行一维的评分表、
 * `### N. 名字` 的 8 个小节），而真正显示给用户的是 `renderMarkdown()`。
 * 这两层之间没有任何编译期关系 —— 规范改一个字、渲染器不认，**两边都不会报错**，
 * 用户看到的就是一屏星号和井号。所以必须拿真渲染器喂一遍。
 *
 * 手法：把 `renderMarkdown` **从源文件里整段取出来**（它是纯字符串操作、不碰 DOM，
 * 所以能在 node 里原样跑），喂进**模拟模型输出**（不是模板、不是规范 —— 是模型
 * 按规范写出来会长的样子），再对 HTML 断言。
 *
 * ⚠ 本脚本的边界：它证明「给这段文字，渲染后是这个 HTML」。它**不证明**
 *   ①模型真会那么写（那是层 15 与守门脚本的边界）；
 *   ②屏幕上真显示了（要 `duipan/drive_bazi_page.js` 那个真浏览器驱动）。
 *
 * 用法：node duipan/check_bazi_render.js
 * 退出码：0 = 全绿；1 = 有用例失败；2 = 提取锚点找不到（源文件重构了，本脚本要跟着改）
 */

'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const N = (f) => path.join(ROOT, f);

const fails = [];
function check(label, cond, detail) {
  if (!cond) fails.push(`${label}：${detail}`);
  console.log(`   ${cond ? '✓' : '✗'} ${label}${cond ? '' : ` —— ${detail}`}`);
}

/**
 * 从源文件里**整段取出** renderMarkdown（到文件末）。
 * 切不到 = 源文件被重构了，当场退出码 2 —— 一个「找不到东西于是什么都没检查」
 * 的检查比没有检查更坏。
 */
function loadRenderMarkdown() {
  const rel = 'build/nginx/js/ui_common.js';
  const src = fs.readFileSync(N(rel), 'utf8');
  const a = src.indexOf('function renderMarkdown(text) {');
  if (a < 0) { console.error(`❌ ${rel} 里找不到 renderMarkdown：源文件重构了，本脚本要跟着改`); process.exit(2); }
  const code = src.slice(a);
  const ctx = { console };
  vm.createContext(ctx);
  try {
    vm.runInContext(code, ctx);
  } catch (e) {
    console.error(`❌ renderMarkdown 取出来了但跑不起来（它是不是开始依赖 DOM 了？）：${e.message}`);
    process.exit(2);
  }
  if (typeof ctx.renderMarkdown !== 'function') {
    console.error('❌ 取出来的代码里没有 renderMarkdown（是不是改成 const/箭头函数了？）');
    process.exit(2);
  }
  return ctx.renderMarkdown;
}

const md = loadRenderMarkdown();

// ══════════════════════════════════════════════════════════════════
// 夹具：模型**按新规范写出来**的样子（不是规范本身）
// ══════════════════════════════════════════════════════════════════
// 刻意包含了几处真实会出现的脏东西：全角空格、破折号、括号里的顿号、
// 行尾「一句话总评」带冒号 —— 这些正是渲染器容易吃进去的地方。
const SAMPLE = [
  '## 一、命盘评分',
  '',
  '直接给分：',
  '- **五行平衡与流通** 得分/15 —— 依据：木火偏旺，金水偏枯，流通不畅',
  '- **日主强弱与调候** 得分/10 —— 依据：日主偏弱、喜印比',
  '- **十神配置与性格才能** 得分/15 —— 依据：食伤透干、官星受制',
  '- **格局层次** 得分/15 —— 依据：正官格、有食伤泄秀',
  '- **事业与财运潜力** 得分/15 —— 依据：财星入库、需大运引动',
  '- **婚姻与感情** 得分/10 —— 依据：夫妻宫受冲',
  '- **健康与体质** 得分/10 —— 依据：火旺水枯，注意心血管',
  '- **大运走势与开运空间** 得分/10 —— 依据：中年后转金水运',
  '',
  '**综合命盘评分：72/100　等级：中上　一句话总评：底子不差，中年后转好。**',
  '',
  '## 二、综合内容',
  '',
  '### 1. 性格与天赋',
  '',
  '你的核心性格是**外柔内刚**。食伤透干，说明你表达欲强、学东西快。',
  '',
  '### 2. 事业与学业',
  '',
  '官星受制，适合**靠手艺吃饭**，不适合纯管理岗。',
  '',
  '### 3. 财运与财富模式',
  '',
  '财星入库，意思是钱得攒着，别追热点。',
  '',
  '### 4. 婚姻与感情',
  '',
  '夫妻宫受冲，婚后有一次**明显的搬迁或分居**。',
  '',
  '### 5. 健康与体质',
  '',
  '火旺水枯。这不是医疗诊断，有症状请就医。',
  '',
  '### 6. 六亲与家庭',
  '',
  '与父亲缘分较薄，与母亲较近。',
  '',
  '### 7. 大运流年',
  '',
  '当前大运（32–41 岁）走壬子，水的力量起来了。',
  '',
  '### 8. 开运与调整建议',
  '',
  '多用蓝黑色，方位选北。',
].join('\n');

const html = md(SAMPLE);

// ══════════════════════════════════════════════════════════════════
console.log('\n① 结构：两大部分与 8 个小节的标题层级');

// `## 一、命盘评分` / `## 二、综合内容` → h2，不能掉成 h1（h1 是页面大标题）
const h2 = (html.match(/<h2 /g) || []).length;
const h1 = (html.match(/<h1 /g) || []).length;
const h3 = (html.match(/<h3 /g) || []).length;
check('两个部分标题渲染成 h2', h2 === 2, `h2 有 ${h2} 个`);
check('报告正文里不许出 h1（那是页面标题的层级）', h1 === 0, `h1 有 ${h1} 个`);

// ★ 这 8 行是整篇的骨架：标题一旦不被渲染成标题，页面上还看得见「性格与天赋」
//   几个字，但整篇会塌成一大段正文，用户根本找不到第几节。
//   真实的坏法有三种，都在这里兜住：① h3 规则失效/被改名 → 该行留成正文里的
//   字面 `### `；② 复制粘贴时把 h3 那条的标签写成 h1 → 层级错乱（下面那条 h1
//   断言就是拦这个的）；③ 模型自己把标题写成 `## ` 或 `#### `。
//   ⚠ 顺带记一笔我写错过的地方：我原先在这里注释说「两条规则先后被调换就会
//     出事」——**没有这回事**。有序列表规则要求行首是数字，`### ` 挡住了它，
//     实测 `^[\s]*\d+\. ` 匹配不上 `### 1. 性格与天赋`。别把不存在的地雷写成注释。
check('8 个小节渲染成 h3', h3 === 8, `h3 有 ${h3} 个`);
const titles = [];
const h3Re = /<h3[^>]*>([^<]*)<\/h3>/g;
let m;
while ((m = h3Re.exec(html))) titles.push(m[1]);
check('h3 里 `N. 名字` 都在（编号没被吃掉、名字没被截断）',
  titles.length === 8 && titles.every((t, i) => t === `${i + 1}. ` + [
    '性格与天赋', '事业与学业', '财运与财富模式', '婚姻与感情',
    '健康与体质', '六亲与家庭', '大运流年', '开运与调整建议'][i]),
  JSON.stringify(titles));

// ══════════════════════════════════════════════════════════════════
console.log('\n② 评分行：一行一维，8 行，都要有项目符号与金色加粗');

const bullets = (html.match(/position:absolute;left:0\.3rem">•</g) || []).length;
check('8 维各成一行、各带一个项目符号', bullets === 8, `项目符号 ${bullets} 个`);
check('每维的名字渲染成加粗（金色）',
  (html.match(/<strong style="color:var\(--accent\)">五行平衡与流通<\/strong>/g) || []).length === 1,
  '找不到「五行平衡与流通」的加粗');
check('「得分/15」原样留在正文里', /得分\/15/.test(html), '分数要求被吃掉了');

// ══════════════════════════════════════════════════════════════════
console.log('\n③ 星号与井号必须被吃干净（漏一个就是用户眼前一个 *）');

// 规范里到处是 `**`，模型也会照用 —— 渲染后正文里**一个都不该剩**。
// 只查正文文本，不查标签属性（属性里没有星号，但这样写更稳）。
const textOnly = html.replace(/<[^>]*>/g, '');
// ⚠ 这里**不能只查 `**`**。我第一版就是这么写的，变异测试当场证明它是橡皮章：
//   把加粗规则整条删掉，`**性格**` 会被后面的斜体规则吃掉中间那两颗 ——
//   变成 `*<em>性格</em>*`，左一个右一个**单星号**，正文里再也找不到连续的 `**`。
//   所以判据要放宽到「一个星号都不许剩」。命理报告正文里不存在合法的字面星号
//   （规范也明令不许用表格），真出现就是渲染失败。
check('正文里没有任何星号漏出来（含被斜体规则吃掉一半的单个 *）',
  !/\*/.test(textOnly), JSON.stringify(textOnly.match(/.{0,20}\*.{0,20}/)));
check('正文里没有剩下行首的 `#`', !/(^|\n)\s*#{1,6}\s/.test(textOnly), '有没被渲染的标题井号');
check('正文里没有剩下 `{{变量}}`（模板没替换干净）', !/\{\{|}}/.test(textOnly), '有没替换的模板变量');
check('没有生成 <table>（规范明令不许用表格，渲染器确实也不支持）',
  !/<table|<\/td>|\|.*\|/.test(html), '出现了表格结构');

// ══════════════════════════════════════════════════════════════════
console.log('\n④ 总评分那一行（含全角空格与多个冒号，最容易渲染成半截）');

const totalLine = /综合命盘评分：72\/100　等级：中上　一句话总评：底子不差，中年后转好。/;
check('总评分行整行都在', totalLine.test(textOnly), '这一行被吃掉了或者被拆了');
check('总评分行是加粗的',
  /<strong style="color:var\(--accent\)">综合命盘评分/.test(html), '没加粗，混在正文里看不出是结论');

// ══════════════════════════════════════════════════════════════════
console.log('\n⑤ 流式半截文本不许崩（边收边渲染，任何前缀都得能出 HTML）');

// 逐字符喂（模拟 SSE 逐块到达）。这里只要求**不抛异常**，
// 不要求中间态好看 —— 用户看到的最终态才是 ①–④ 那几条在管。
let threw = '';
for (let i = 1; i <= SAMPLE.length; i++) {
  try { md(SAMPLE.slice(0, i)); } catch (e) { threw += `${i}:${e.message} `; break; }
}
check('从 1 个字到整篇，逐字符渲染都不抛异常', threw === '', threw);

// ══════════════════════════════════════════════════════════════════

console.log('');
if (fails.length) {
  console.log(`❌ 八字报告渲染检查：${fails.length} 条失败`);
  fails.forEach((f) => console.log(`   ✗ ${f}`));
  process.exit(1);
}
console.log('✅ 八字报告渲染检查：全部通过');
