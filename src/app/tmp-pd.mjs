import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:500,height:900} })).newPage();
const errs=[];
p.on('pageerror', e=>errs.push('PAGEERROR: '+e.message));
p.on('console', m=>{ if(m.type()==='error') errs.push('CONSOLE: '+m.text()); });
await p.goto('http://127.0.0.1:8123/mhys/', { waitUntil:'networkidle' });
await p.locator('button:has-text("开始排盘")').first().click().catch(()=>{});
await p.waitForTimeout(2500);
console.log(errs.slice(0,6).join('\n')||'(无错误)');
console.log('area:', (await p.locator('#resultArea').innerText().catch(()=>'(无 resultArea)')).slice(0,120));
b.close();
